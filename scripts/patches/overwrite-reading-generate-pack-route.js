export async function POST(req: Request) {
  try {
    const body = await readBodyJson(req);
    const n = normalizeInput(body);

    // If we only got a URL, try fetching text (best-effort).
    if (!n.text && n.sourceUrl) {
      const fetched = await fetchUrlText(n.sourceUrl);
      if (fetched && fetched.trim()) n.text = fetched.trim();
    }

    if (!n.text && !n.imageDataUrl) {
      return NextResponse.json(
        { error: "Missing input text (material/text/url/html) or imageDataUrl." },
        { status: 400 }
      );
    }

    const apiKey = process.env.OPENAI_API_KEY;
    if (!apiKey) {
      return NextResponse.json({ error: "Missing OPENAI_API_KEY." }, { status: 500 });
    }

    const modelName = process.env.OPENAI_MODEL || "gpt-4o-mini";
    const client = new OpenAI({ apiKey });

    const system = buildSystemPrompt(n);
    const user = buildUserInstruction(n);

    const userContent = n.imageDataUrl
      ? [
          { type: "input_text", text: user },
          { type: "input_image", image_url: n.imageDataUrl },
        ]
      : user;

    const resp = await client.responses.create({
      model: modelName,
      input: [
        { role: "system", content: system },
        { role: "user", content: userContent as any },
      ],
      // IMPORTANT: Responses API uses text.format (NOT response_format)
      text: {
        format: {
          type: "json_schema",
          strict: true,
          schema: buildJsonSchema(),
        },
      },
      temperature: 0.6,
      max_output_tokens: 4000,
    });

    const raw = extractResponseText(resp);
    if (!raw) {
      return NextResponse.json({ error: "Empty model response." }, { status: 502 });
    }

    let pack: any;
    try {
      pack = JSON.parse(raw);
    } catch {
      pack = (resp as any)?.output_parsed ?? null;
      if (!pack) {
        return NextResponse.json(
          { error: "Model returned non-JSON text (unexpected with json_schema).", raw: raw.slice(0, 5000) },
          { status: 502 }
        );
      }
    }

    return NextResponse.json({ pack });
  } catch (err: any) {
    const msg = typeof err?.message === "string" ? err.message : String(err);
    return NextResponse.json({ error: msg }, { status: 500 });
  }
}
